"""Low-level helpers for building, traversing and materialising nested lists.

These functions are the recursive workhorses behind :class:`~structs.array.array.Array`;
they operate on plain Python nested lists rather than on ``Array`` instances.
"""

from __future__ import annotations

from itertools import product
from typing import Any, Callable, Iterator, List, Sequence, Tuple

from structs.dtypes import NestedList, Scalar, Shape

__all__ = ["build_index", "indices", "set_nested", "newarr", "zeroes"]

#: A single ``(axes, values)`` pair: parallel sequences of equal length.
AxisValueGroup = Tuple[Sequence[int], Sequence[Any]]


def build_index(ndim: int, *groups: AxisValueGroup) -> tuple[int, ...]:
    """Build a multi-dimensional index tuple by mapping axis positions to values.

    Each positional group is an ``(axes, values)`` pair. ``axes[i]`` names the
    dimension to write and ``values[i]`` is the value placed there; both
    sequences must be the same length. Dimensions not covered by any group keep
    the default ``0``.

    Args:
        ndim: Rank of the array being indexed; the length of the result tuple.
        *groups: Zero or more ``(axes, values)`` pairs, applied left to right so
            a later group overwrites an earlier one on the same axis.

    Returns:
        tuple[int, ...]: An index tuple of exactly ``ndim`` elements, zero-padded
        where no group supplied a value.

    Example:
        >>> build_index(3, ([0, 1], [2, 5]))
        (2, 5, 0)
    """
    idx: List[int] = [0] * ndim

    for axes, values in groups:
        for axis, value in zip(axes, values):
            idx[axis] = value

    return tuple(idx)


def indices(shape: Shape) -> Iterator[tuple[int, ...]]:
    """Yield all multi-dimensional index tuples for a given array shape.

    Iteration happens in C order: the last dimension varies fastest.

    Args:
        shape: Fully resolved shape, one ``int`` per dimension. An empty
            shape ``()`` denotes a 0-d (scalar) array and yields a single
            empty tuple.

    Yields:
        tuple[int, ...]: One index tuple per element, each of length
        ``len(shape)``, with every component in ``range(shape[i])``.

    Example:
        >>> list(indices((2, 2)))
        [(0, 0), (0, 1), (1, 0), (1, 1)]
    """
    if shape == ():
        yield ()
    else:
        yield from product(*(range(s) for s in shape))


def zeroes(shape: Shape) -> NestedList:
    """Recursively create nested lists filled with zeros according to shape.

    Args:
        shape: Fully resolved shape. ``()`` produces the scalar ``0``;
            otherwise one nested ``list`` is created per dimension.

    Returns:
        NestedList: Either the int ``0`` for an empty shape, or nested lists of
        matching depth whose innermost elements are all ``0``.

    Example:
        >>> zeroes((2, 2))
        [[0, 0], [0, 0]]
    """
    if len(shape) == 0:
        return 0

    return [zeroes(shape[1:]) for _ in range(shape[0])]


def set_nested(
    lst: Any, idx: Sequence[int], value: Any
) -> Any:
    """Set value at a specific multi-dimensional index within nested lists.

    The assignment is in-place for every traversed level; the mutated container
    is also returned for convenience.

    Args:
        lst: Nested list (or scalar, when ``idx`` is empty) to modify in place.
        idx: Sequence of positions, one per dimension. An empty ``idx`` makes
            this a no-op that simply returns ``value``.
        value: Payload to store at the target position.

    Returns:
        The innermost container actually written into, not the outermost
        ``lst`` — e.g. ``[[0, 0], [0, 0]]`` in the example below. Returns
        ``value`` itself when ``idx`` is empty.

    Raises:
        IndexError: If ``idx`` addresses a position outside ``lst``.

    Example:
        >>> data = [[0, 0], [0, 0]]
        >>> _ = set_nested(data, [1, 0], 7)
        >>> data
        [[0, 0], [7, 0]]
    """
    if not idx:
        return value
    for i in idx[:-1]:
        lst = lst[i]
    lst[idx[-1]] = value
    return lst


# Deprecated: use Array.full instead.
def newarr(shape: Shape, fill: Callable[[], Scalar]) -> NestedList:
    """(Deprecated: use ``Array.full``) Recursively create nested lists filled
    with values generated by a fill callable.

    Args:
        shape: Fully resolved shape; ``()`` yields a single scalar.
        fill: Zero-argument callable invoked once per innermost element, so
            every position can receive a distinct value.

    Returns:
        NestedList: Nested lists of matching depth, or a scalar for ``()``.

    Example:
        >>> counter = iter(range(10))
        >>> newarr((2, 2), lambda: next(counter))
        [[0, 1], [2, 3]]
    """
    if len(shape) == 0:
        return fill()

    return [newarr(shape[1:], fill) for _ in range(shape[0])]